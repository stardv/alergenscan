/// One recognisable phrase on an ingredient label.
///
/// `allergen == nil` marks a **neutral phrase**: something that must be
/// recognised and consumed so that a shorter term cannot match inside it,
/// but which flags nothing. "Coconut milk" is the canonical example — it has
/// to swallow the word "milk" before `milk` gets a chance to match it.
public struct Term {
    public let phrase: String
    /// Empty means a neutral phrase: recognised and consumed, but flags nothing.
    public let allergens: [Allergen]

    public init(_ phrase: String, _ allergen: Allergen?) {
        self.phrase = phrase
        self.allergens = allergen.map { [$0] } ?? []
    }

    /// For ingredients that genuinely imply more than one allergen at once.
    /// Marzipan is almonds *and* egg white; surimi is fish *and* egg.
    public init(_ phrase: String, _ allergens: [Allergen]) {
        self.phrase = phrase
        self.allergens = allergens
    }
}

